"""
app.py
Streamlit web UI for the support ticket tagging pipeline.

Paste raw ticket text in, see predicted priority + department + a draft
response, generated by the same trained models used everywhere else in
this project (models/*.pkl) - no separate/duplicated logic.

Run locally:  streamlit run app.py
Deploy:       push this repo to Hugging Face Spaces (see README_DEPLOY.md)
"""

import streamlit as st
import csv
import os
from datetime import datetime
from predict_demo import (
    predict_ticket_with_confidence, draft_response, SLA, explain_department_prediction,
)
from pii_redaction import redact_pii

CONFIDENCE_THRESHOLD = 0.60  # Suggestion #1: below this, flag for manual review
CORRECTIONS_FILE = "corrections.csv"  # Suggestion #3: feedback loop

st.set_page_config(page_title="Support Ticket Auto-Tagger", page_icon="🎫", layout="centered")

st.title("🎫 Support Ticket Auto-Tagger")
st.caption(
    "Paste a raw customer support ticket below. The app predicts a priority "
    "and department, then drafts a first-pass response an agent can review "
    "and send."
)

with st.expander("ℹ️ About this project / known limitations", expanded=False):
    st.markdown(
        """
This is a free, self-trained pipeline (TF-IDF + a calibrated linear model)
built on a real 12,122-row support-ticket dataset (English subset of
Kaggle's "Multilingual Customer Support Tickets" dataset). Honest
performance notes from testing on real held-out data — this is not a claim
of 100% accuracy, no real classifier on this data reaches that:

- **Department routing**: ~97% accuracy, macro-F1 ~0.91, using a
  `class_weight='balanced'` classifier over the full TF-IDF vocabulary.
  Remaining errors are mostly Billing-labeled tickets that mention no
  billing-related content at all (e.g. security or data-analytics topics
  filed under Billing in the source data) — a dataset-content limit, not
  a fixable routing bug.
- **Priority prediction**: ~76% accuracy, macro-F1 ~0.74 — Low-priority
  recall in particular improved from 17% to 58% after the full accuracy
  pass. This remains the weaker of the two tasks; a ticket can still read
  as more urgent to a human than the model scores it, so it's worth a
  sanity check on anything that looks off.
- **Draft response**: reads as much of the ticket as reasonably fits
  (not just the first sentence), per real user-testing feedback.
- **Confidence flagging**: predictions the model is least sure about are
  flagged for a manual look rather than silently presented as certain —
  the app shows this as a plain warning, not a numeric score.
- **Explainability**: expand "Why this department?" to see which words
  in the ticket actually drove the routing decision (exact, computed
  directly from the model's own learned weights — not an approximation).
- **Feedback loop**: agents can correct a wrong department prediction;
  corrections are saved to `corrections.csv` for future retraining, with
  emails/phone numbers/card numbers/order numbers masked before they're
  written.
        """
    )

default_example = (
    "My order #482910 hasn't arrived and tracking hasn't updated in 5 days, "
    "I need it urgently!"
)

ticket_text = st.text_area(
    "Ticket text",
    value=st.session_state.get("ticket_text", ""),
    placeholder=default_example,
    height=150,
)

run = st.button("Analyze ticket", type="primary", use_container_width=True)

DEPARTMENTS = ["Billing", "Technical support", "Delivery"]


def save_correction(ticket_text, predicted_department, corrected_department, predicted_priority):
    """Suggestion #3: append agent corrections to a CSV for future retraining.

    Storage schema (corrections.csv, created with a header on first write,
    appended thereafter -- this is the project's only runtime "database"):
        timestamp             ISO-8601 local time of the submission
        ticket_text           PII-masked ticket text
        predicted_priority    High | Medium | Low   (model output)
        predicted_department  Billing | Technical support | Delivery (model output)
        corrected_department  same values (agent's choice; equal to the
                              prediction when the agent confirms it)
    Error boundary: no locking, so this is single-user safe only; an OS
    error (read-only disk, permissions) propagates and Streamlit shows it
    in the page. Only the department is ever corrected -- priority is
    stored as predicted, which is why merge_corrections.py tags merged
    rows priority_verified=False.

    ticket_text is redacted (pii_redaction.redact_pii) before it's written:
    emails, phone numbers, card numbers, and order/account/reference
    numbers are masked, since this file is a plain-text CSV on disk with
    no encryption. See Section 10 of the project report -- this does not
    detect names or addresses, only the categories redact_pii covers.
    """
    file_exists = os.path.exists(CORRECTIONS_FILE)
    safe_ticket_text, _ = redact_pii(ticket_text)
    with open(CORRECTIONS_FILE, "a", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        if not file_exists:
            writer.writerow(["timestamp", "ticket_text", "predicted_priority",
                              "predicted_department", "corrected_department"])
        writer.writerow([datetime.now().isoformat(), safe_ticket_text, predicted_priority,
                          predicted_department, corrected_department])


# ---- Error boundaries in the request flow (top to bottom) -----------------
#  1. Blank / whitespace input      -> warning, pipeline is not run.
#  2. No usable words (emoji, digits, punctuation) -> insufficient_text
#     error banner; confidences forced to 0.0 upstream.
#  3. Confidence < CONFIDENCE_THRESHOLD -> "needs a second look" warning
#     (the number itself is never shown to the agent).
#  4. Medium/Low priority           -> reminder that priority is the weaker task.
#  5. No explainable words          -> "extra caution" message instead of a list.
# PII is masked before anything is quoted in the draft or written to disk.
if run:
    if not ticket_text.strip():
        st.warning("Please paste some ticket text first.")
    else:
        with st.spinner("Running the pipeline..."):
            result = predict_ticket_with_confidence(ticket_text)
            priority = result["priority"]
            department = result["department"]
            pri_conf = result["priority_confidence"]
            dep_conf = result["department_confidence"]
            insufficient_text = result["insufficient_text"]
            response = draft_response(priority, department, raw_text=ticket_text)
            top_words = explain_department_prediction(ticket_text)

        st.divider()
        st.subheader("Predictions")

        pcol, dcol, scol = st.columns(3)
        priority_color = {"High": "🔴", "Medium": "🟡", "Low": "🟢"}
        pcol.metric("Priority", f"{priority_color.get(priority, '')} {priority}")
        dcol.metric("Department", department)
        scol.metric("Target SLA", SLA[priority])

        # Edge case: text with no vocabulary overlap at all (empty, emoji-only,
        # punctuation/number-only, whitespace-only). On an all-zero feature
        # vector the model still reports a "confident" prediction from its
        # class priors alone, so this is checked and flagged separately
        # rather than folded into the ordinary confidence check below.
        if insufficient_text:
            st.error(
                "⚠️ **Not enough usable text to make a prediction.** The ticket text "
                "contains no recognizable words, so the priority/department shown "
                "above are not based on any signal in this ticket — please write a "
                "ticket description before relying on these results.",
                icon="🚫",
            )
        # Suggestion #1: confidence thresholding. The underlying probability
        # is used to decide whether to flag this, but is never shown as a
        # number in the UI — just a plain-language "needs a second look" or
        # "no concerns" signal.
        elif pri_conf < CONFIDENCE_THRESHOLD or dep_conf < CONFIDENCE_THRESHOLD:
            low_fields = []
            if pri_conf < CONFIDENCE_THRESHOLD:
                low_fields.append("priority")
            if dep_conf < CONFIDENCE_THRESHOLD:
                low_fields.append("department")
            st.warning(
                f"⚠️ **This one needs a second look before you send it.** "
                f"The model isn't confident about: {', '.join(low_fields)}. "
                f"Don't send the draft below without checking it first.",
                icon="⚠️",
            )
        elif priority in ("Medium", "Low"):
            st.info(
                "Priority predictions are generally less reliable than department "
                "predictions on this dataset (see 'About this project' above) — "
                "worth a quick sanity check.",
                icon="ℹ️",
            )

        # Suggestion #4: explainability
        with st.expander("🔍 Why this department?", expanded=False):
            if top_words:
                st.write("These words in the ticket pushed the model toward "
                         f"**{department}**, ranked by how much each contributed:")
                for word, contribution in top_words:
                    bar_width = min(int(contribution * 20), 100)
                    st.markdown(
                        f"`{word}` " + "🟦" * max(bar_width // 10, 1) + f"  ({contribution:.2f})"
                    )
            else:
                st.write(
                    "No single strong keyword drove this prediction — the model's "
                    "decision here comes from a broad combination of weaker signals "
                    "rather than a few standout words. Treat this one with extra caution."
                )

        st.subheader("Draft response")
        st.text_area("Editable draft — copy, adjust, and send:", value=response, height=200)

        # Suggestion #3: feedback loop UI
        st.subheader("Was this routed correctly?")
        fcol1, fcol2 = st.columns([2, 1])
        with fcol1:
            corrected = st.selectbox(
                "Correct department (only change this if the prediction above is wrong):",
                options=DEPARTMENTS,
                index=DEPARTMENTS.index(department) if department in DEPARTMENTS else 0,
                key="correction_select",
            )
        with fcol2:
            st.write("")
            st.write("")
            if st.button("Submit correction", use_container_width=True):
                save_correction(ticket_text, department, corrected, priority)
                if corrected == department:
                    st.success("Thanks — logged as confirmed correct.")
                else:
                    st.success(f"Thanks — logged as {department} → {corrected}. "
                               f"This will help retrain the model.")
        st.caption(
            "Emails, phone numbers, card numbers, and order/account/reference "
            "numbers in the ticket text are masked before anything is written "
            "to corrections.csv."
        )

st.divider()
st.caption(
    "Model: TF-IDF + calibrated LinearSVC, trained on data/support_tickets_real_v2.csv. "
    "Not connected to any live ticketing system — for demo/review purposes. "
    "Agent corrections are saved locally to corrections.csv (PII-masked)."
)
